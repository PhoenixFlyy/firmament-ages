package dev.firmages.core.client.immersion;

import com.google.gson.JsonParser;
import dev.firmages.core.FirmagesCore;
import dev.firmages.core.age.AgeId;
import dev.firmages.core.immersion.EmiAgeView;
import net.minecraft.core.Holder;
import net.minecraft.core.Registry;
import net.minecraft.core.registries.BuiltInRegistries;
import net.minecraft.core.registries.Registries;
import net.minecraft.resources.ResourceKey;
import net.minecraft.resources.ResourceLocation;
import net.minecraft.server.packs.resources.Resource;
import net.minecraft.server.packs.resources.ResourceManager;
import net.minecraft.server.packs.resources.ResourceManagerReloadListener;
import net.minecraft.tags.TagKey;
import net.minecraft.world.item.Item;
import net.minecraft.world.level.material.Fluid;
import net.neoforged.api.distmarker.Dist;
import net.neoforged.bus.api.SubscribeEvent;
import net.neoforged.fml.ModList;
import net.neoforged.fml.common.EventBusSubscriber;
import net.neoforged.neoforge.client.event.ClientPlayerNetworkEvent;
import net.neoforged.neoforge.client.event.RegisterClientReloadListenersEvent;
import net.neoforged.neoforge.event.TagsUpdatedEvent;

import java.io.Reader;
import java.util.ArrayList;
import java.util.Collection;
import java.util.IdentityHashMap;
import java.util.List;
import java.util.Map;
import java.util.Optional;
import java.util.Set;

/**
 * The live {@link EmiAgeView} of this client (SPEC §21): the player's Age stages (ProgressiveStages
 * {@code ClientStageCache}, which starts the EMI reload when they change; without ProgressiveStages every Age up to the
 * {@code firmages:age_status} Age), the synced {@code firmages:age_items|age_fluids/<age>} tags and
 * {@code assets/firmages/age_namespaces.json} (shipped through {@code kubejs/assets}, generated by
 * {@code dev/gen_stage_locks.py}). Built on demand and cached until the stages, the tags or the namespace file change.
 * Thread-safe: EMI builds it on its reload thread, Ponder on the render thread.
 */
public final class ClientAgeView {
    static final ResourceLocation NAMESPACES_FILE = ResourceLocation.fromNamespaceAndPath(FirmagesCore.MOD_ID, "age_namespaces.json");
    private static final String ITEM_PREFIX = "age_items/";
    private static final String FLUID_PREFIX = "age_fluids/";

    private static volatile Map<String, AgeId> namespaces = Map.of();
    private static volatile int tagGeneration;
    private static EmiAgeView cached;
    private static Object cachedKey;

    private ClientAgeView() {}

    /** The view for the current stages and tags. */
    public static synchronized EmiAgeView current() {
        Collection<String> stages = stagePaths();
        Object key = List.of(Set.copyOf(stages), tagGeneration, namespaces);
        if (cached == null || !key.equals(cachedKey)) {
            long t0 = System.nanoTime();
            cached = EmiAgeView.build(stages, namespaces,
                BuiltInRegistries.ITEM, i -> BuiltInRegistries.ITEM.getKey(i).toString(), tagAges(BuiltInRegistries.ITEM, Registries.ITEM, ITEM_PREFIX)::get,
                BuiltInRegistries.FLUID, f -> BuiltInRegistries.FLUID.getKey(f).toString(), tagAges(BuiltInRegistries.FLUID, Registries.FLUID, FLUID_PREFIX)::get);
            cachedKey = key;
            FirmagesCore.LOGGER.debug("Client Age view {} built in {} ms", cached.summary(), (System.nanoTime() - t0) / 1_000_000L);
        }
        return cached;
    }

    /** The item is of a locked Age for this player (Ponder index and tag screens). */
    public static boolean itemLocked(Item item) {
        return current().itemLocked(item);
    }

    public static Map<String, AgeId> namespaces() {
        return namespaces;
    }

    private static Collection<String> stagePaths() {
        if (ModList.get().isLoaded("progressivestages")) {
            try {
                return PsStages.paths();
            } catch (RuntimeException | LinkageError e) {
                FirmagesCore.LOGGER.warn("Client Age view: cannot read the ProgressiveStages stages ({}), using the Age status", e.toString());
            }
        }
        List<String> out = new ArrayList<>();
        AgeId current = ClientAgeStatus.get().age();
        for (AgeId a : AgeId.all()) if (a.ordinal() <= current.ordinal()) out.add(a.id());
        return out;
    }

    /** Object to its Age tag path ({@code age_3}, {@code disabled}); objects in no Age tag are absent. */
    private static <T> Map<T, String> tagAges(Registry<T> registry, ResourceKey<? extends Registry<T>> key, String prefix) {
        Map<T, String> out = new IdentityHashMap<>();
        List<String> ages = new ArrayList<>();
        for (AgeId a : AgeId.all()) ages.add(a.id());
        ages.add(EmiAgeView.DISABLED);
        for (String age : ages) {
            TagKey<T> tag = TagKey.create(key, ResourceLocation.fromNamespaceAndPath(FirmagesCore.MOD_ID, prefix + age));
            registry.getTag(tag).ifPresent(set -> {
                for (Holder<T> h : set) {
                    // disabled wins over an Age, as in the server's AgeIndex
                    if (EmiAgeView.DISABLED.equals(age)) out.put(h.value(), age);
                    else out.putIfAbsent(h.value(), age);
                }
            });
        }
        return out;
    }

    static Map<String, AgeId> readNamespaces(ResourceManager rm) {
        Optional<Resource> res = rm.getResource(NAMESPACES_FILE);
        if (res.isEmpty()) {
            FirmagesCore.LOGGER.warn("{} is missing: the recipe viewer hides locked items, but not locked mods' categories", NAMESPACES_FILE);
            return Map.of();
        }
        try (Reader r = res.get().openAsReader()) {
            return Map.copyOf(EmiAgeView.parseNamespaces(JsonParser.parseReader(r)));
        } catch (Exception e) {
            FirmagesCore.LOGGER.warn("Cannot read {}: {}", NAMESPACES_FILE, e.toString());
            return Map.of();
        }
    }

    /** ProgressiveStages classes stay behind this holder, so the view works without the mod. */
    private static final class PsStages {
        static Collection<String> paths() {
            List<String> out = new ArrayList<>();
            for (var id : com.enviouse.progressivestages.client.ClientStageCache.getStages()) out.add(id.getPath());
            return out;
        }
    }

    @EventBusSubscriber(modid = FirmagesCore.MOD_ID, value = Dist.CLIENT)
    public static final class ModEvents {
        private ModEvents() {}

        @SubscribeEvent
        public static void reloadListeners(RegisterClientReloadListenersEvent event) {
            event.registerReloadListener((ResourceManagerReloadListener) rm -> namespaces = readNamespaces(rm));
        }
    }

    @EventBusSubscriber(modid = FirmagesCore.MOD_ID, value = Dist.CLIENT)
    public static final class GameEvents {
        private GameEvents() {}

        @SubscribeEvent
        public static void tags(TagsUpdatedEvent event) {
            if (event.getUpdateCause() == TagsUpdatedEvent.UpdateCause.CLIENT_PACKET_RECEIVED) tagGeneration++;
        }

        @SubscribeEvent
        public static void loggedOut(ClientPlayerNetworkEvent.LoggingOut event) {
            synchronized (ClientAgeView.class) {
                cached = null;
                cachedKey = null;
            }
        }
    }
}
