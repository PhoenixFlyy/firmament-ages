    /** {@code starfall carve <id>}: a temporary ticket on the box, the impact now if it is still ahead, then the carve. */
    public static boolean carveNow(ServerLevel ow, long id) {
        SkySavedData d = SkySavedData.get(ow.getServer());
        Optional<StarfallSite> o = d.site(id);
        if (o.isEmpty() || !o.get().open()) return false;
        StarfallSite s = o.get();
        if (s.origin == StarfallSite.Origin.LIVE && !s.impacted) impact(ow, d, s);
        int reach = CraterCarver.plan(s).reach();
        ChunkPos centre = new ChunkPos(s.x >> 4, s.z >> 4);
        ow.getChunkSource().addRegionTicket(TICKET, centre, 2 + ((reach + 15) >> 4), centre);
        DeferredSites.register(Level.OVERWORLD, KIND, s.id, s.chunks(reach));
        return true;
    }

    /** {@code starfall cool|heat <id>}: cools the site now or makes it glow for {@code starfall.coolTicks} from now. */
    public static boolean setHot(ServerLevel ow, long id, boolean hot) {
        SkySavedData d = SkySavedData.get(ow.getServer());
        Optional<StarfallSite> o = d.site(id);
        if (o.isEmpty()) return false;
        StarfallSite s = o.get();
        long now = ow.getGameTime();
        s.coolsAt = hot ? now + ServerConfig.starfallCoolTicks() : now;
        d.setDirty();
        if (s.core != null && ow.isLoaded(s.core) && ow.getBlockEntity(s.core) instanceof StarfallCoreBlockEntity be) {
            be.setCooling(s.id, s.coolsAt);
            be.check();
        }
        return true;
    }
