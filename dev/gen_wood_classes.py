HAMMER = {"type": "minecraft:item", "name": "minecraft:stick",
          "conditions": [{"condition": "minecraft:match_tool", "predicate": {"items": "#c:tools/hammer"}}],
          "functions": [{"function": "minecraft:set_count", "count": {"type": "minecraft:uniform", "min": 1, "max": 4}}]}


def trunk_table(block, self_item, class_log):
    return {"type": "minecraft:block", "pools": [{
        "rolls": 1, "conditions": [{"condition": "minecraft:survives_explosion"}],
        "entries": [{"type": "minecraft:alternatives", "children": [
            HAMMER,
            {"type": "minecraft:item", "name": self_item, "conditions": [
                {"condition": "minecraft:block_state_property", "block": block, "properties": {"branch_direction": "none"}}]},
            {"type": "minecraft:item", "name": class_log}]}]}]}


def ancient_table(class_log):
    return {"type": "minecraft:block", "pools": [{
        "rolls": 1, "conditions": [{"condition": "minecraft:survives_explosion"}],
        "entries": [{"type": "minecraft:alternatives", "children": [
            HAMMER,
            {"type": "minecraft:item", "name": class_log,
             "conditions": [{"condition": "minecraft:random_chance", "chance": 0.7}]}]}]}]}


