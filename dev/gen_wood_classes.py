def render(o):
    return json.dumps(o, indent=2) + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--mods", default=os.path.join(REPO, "test-server", "mods"))
    a = ap.parse_args()
    table = tomllib.loads(open(TABLE, encoding="utf-8").read())
    reg_items = set(json.load(open(REGISTRY, encoding="utf-8"))["items"])
    files, body = build(table, reg_items, forest_biomes(a.mods))
    dirty = []
    for path, obj in sorted(files.items()):
        text = render(obj)
        old = open(path, encoding="utf-8").read() if os.path.exists(path) else None
        if old != text:
            dirty.append(os.path.relpath(path, REPO).replace(os.sep, "/"))
            if not a.check:
                os.makedirs(os.path.dirname(path), exist_ok=True)
                with open(path, "w", encoding="utf-8", newline="\n") as f:
                    f.write(text)
    src = open(CONSTANTS, encoding="utf-8").read()
    block = f"{MARK_BEGIN}\n// Wood classes ({HEADER}).\n{body}{MARK_END}\n"
    if MARK_BEGIN in src:
        new = re.sub(re.escape(MARK_BEGIN) + r".*?" + re.escape(MARK_END) + r"\n", lambda m: block, src, flags=re.S)
    else:
        new = src.rstrip("\n") + "\n\n" + block
    if new != src:
        dirty.append(os.path.relpath(CONSTANTS, REPO).replace(os.sep, "/"))
        if not a.check:
            with open(CONSTANTS, "w", encoding="utf-8", newline="\n") as f:
                f.write(new)
    print(f"wood classes: {len(table['classes'])} classes, {len(files)} data files, {len(dirty)} out of date")
    if a.check and dirty:
        print("out of date:", ", ".join(dirty[:20]))
        sys.exit(1)


if __name__ == "__main__":
    main()
