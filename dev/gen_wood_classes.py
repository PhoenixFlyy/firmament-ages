def die(msg):
    print("ERROR:", msg)
    sys.exit(2)


def ids(ns_sp, kind):
    ns, sp = ns_sp.split(":")
    return f"{ns}:wood/{kind}/{sp}"


def vanilla(k, nether, kind):
    """Vanilla item of a class: log, wood, stripped_log, stripped_wood, planks, slab, stairs, sapling."""
    if nether:
        return {"log": f"minecraft:{k}_stem", "wood": f"minecraft:{k}_hyphae",
                "stripped_log": f"minecraft:stripped_{k}_stem", "stripped_wood": f"minecraft:stripped_{k}_hyphae",
                "planks": f"minecraft:{k}_planks", "slab": f"minecraft:{k}_slab", "stairs": f"minecraft:{k}_stairs",
                "sapling": None, "logs_tag": f"minecraft:{k}_stems"}[kind]
    return {"log": f"minecraft:{k}_log", "wood": f"minecraft:{k}_wood", "stripped_log": f"minecraft:stripped_{k}_log",
            "stripped_wood": f"minecraft:stripped_{k}_wood", "planks": f"minecraft:{k}_planks",
            "slab": f"minecraft:{k}_slab", "stairs": f"minecraft:{k}_stairs",
            "sapling": "minecraft:mangrove_propagule" if k == "mangrove" else f"minecraft:{k}_sapling",
            "logs_tag": f"minecraft:{k}_logs"}[kind]


def tag_json(values):
    return {"replace": False, "values": [{"id": v, "required": False} if not v.startswith("#") else v for v in values]}


