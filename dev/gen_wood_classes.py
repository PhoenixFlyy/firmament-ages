def would_survive(sapling):
    return {"type": "minecraft:block_predicate_filter",
            "predicate": {"type": "minecraft:would_survive", "state": {"Name": sapling, **(
                {"Properties": {"stage": "0"}} if not sapling.endswith("propagule") else {})}}}


