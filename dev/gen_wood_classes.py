def forest_biomes(mods_dir):
    """TFC biomes whose large features hold tfc:forest (TFC jar), cached in dev/data/tfc_forest_biomes.json."""
    jars = sorted(glob.glob(os.path.join(mods_dir, "TerraFirmaCraft-*.jar")))
    if not jars:
        if os.path.isfile(BIOME_LIST):
            return json.load(open(BIOME_LIST, encoding="utf-8"))["biomes"]
        die(f"no TFC jar in {mods_dir} and no {os.path.relpath(BIOME_LIST, REPO)}")
    z = zipfile.ZipFile(jars[-1])
    out = []
    pre = "data/tfc/tags/worldgen/placed_feature/in_biome/large_features/"
    for n in sorted(z.namelist()):
        if n.startswith(pre) and n.endswith(".json"):
            vals = json.loads(z.read(n)).get("values", [])
            if "tfc:forest" in vals:
                out.append("tfc:" + n[len(pre):-5])
    return out


# ------------------------------------------------------------------------------------------------ build
def build(table, reg_items, biomes):
    files = {}
    classes = table["classes"]
    all_species = []
    js = {}

    def need(i):
        if i not in reg_items:
            die(f"{i} is not in dev/data/registry.json")
        return i

    for k, c in classes.items():
        nether = bool(c.get("nether"))
        clog = need(vanilla(k, nether, "log"))
        lead = c["lead"]
        if lead not in c["species"]:
            die(f"[classes.{k}] lead {lead} is not one of its species")
        entries = []
        for kind_list, variant in ((c["species"], False), (c.get("variants", []), True)):
            for s in kind_list:
                ns, sp = s.split(":")
                all_species.append(s)
                for kind in ("log", "wood"):
                    block = need(ids(s, kind))
                    files[os.path.join(KDATA, ns, "loot_table", "blocks", "wood", kind, f"{sp}.json")] = \
                        trunk_table(block, block, clog)
                anc = f"afc:wood/log/ancient_{sp}"
                if anc in reg_items:
                    for kind in ("log", "wood"):
                        files[os.path.join(KDATA, "afc", "loot_table", "blocks", "wood", kind, f"ancient_{sp}.json")] = \
                            ancient_table(clog)
                e = {"id": s, "log": ids(s, "log"), "wood": ids(s, "wood"), "sapling": need(ids(s, "sapling")),
                     "variant": variant}
                if not variant:
                    e["planks"] = need(ids(s, "planks"))
                entries.append(e)
        v = {kind: vanilla(k, nether, kind) for kind in
             ("log", "wood", "stripped_log", "stripped_wood", "planks", "slab", "stairs", "sapling", "logs_tag")}
        for kind in ("log", "wood", "stripped_log", "stripped_wood", "planks", "slab", "stairs"):
            need(v[kind])
        lns, lsp = lead.split(":")
        js[k] = {"nether": nether, "vanilla": v, "lead": {
            "id": lead, "logs_tag": f"{lns}:{lsp}_logs", "log": ids(lead, "log"), "stripped_log": ids(lead, "stripped_log"),
            "planks": ids(lead, "planks"), "slab": ids(lead, "planks") + "_slab", "stairs": ids(lead, "planks") + "_stairs",
            "lumber": need(ids(lead, "lumber"))}, "species": entries}
        # T2 fuel
        dur, temp, purity = c["fuel"]
        fuel = {"duration": dur, "ingredient": {"tag": v["logs_tag"]}, "temperature": float(temp)}
        if purity != 1.0:
            fuel["purity"] = purity
        files[os.path.join(KDATA, "firmages", "tfc", "fuel", f"{k}_logs.json")] = fuel
        if not nether:
            pf = {"duration": round(dur * 0.4), "ingredient": {"item": v["planks"]}, "temperature": float(temp) + 50.0}
            if purity != 1.0:
                pf["purity"] = purity
            files[os.path.join(KDATA, "firmages", "tfc", "fuel", f"{k}_planks.json")] = pf
        # T3 class tags: vanilla items and the lead species only (another species in a lead recipe would match twice)
        base = os.path.join(KDATA, "firmages", "tags", "item", "wood_class", k)
        files[os.path.join(base, "logs.json")] = tag_json(["#" + v["logs_tag"], "#" + js[k]["lead"]["logs_tag"]])
        files[os.path.join(base, "stripped_logs.json")] = tag_json(
            [v["stripped_log"], v["stripped_wood"], ids(lead, "stripped_log"), ids(lead, "stripped_wood")])
        files[os.path.join(base, "planks.json")] = tag_json([v["planks"], ids(lead, "planks")])
        files[os.path.join(base, "slabs.json")] = tag_json([v["slab"], ids(lead, "planks") + "_slab"])

    dup = {s for s in all_species if all_species.count(s) > 1}
    if dup:
        die(f"species in more than one class: {sorted(dup)}")

    # tannin: a class tans when one of its species does (TFC and AFC tfc:tannin_logs)
    tannin_species = set(table.get("tannin_species", []))
    tannin = [x for k, c in classes.items() if not c.get("nether") and set(c["species"] + c.get("variants", [])) & tannin_species
              for x in (vanilla(k, False, "log"), vanilla(k, False, "wood"))]
    T = os.path.join(KDATA, "{ns}", "tags", "{kind}", "{path}.json")
    files[T.format(ns="tfc", kind="item", path="tannin_logs")] = tag_json(tannin)
    files[T.format(ns="firmages", kind="item", path="vanilla_planks")] = tag_json(
        [vanilla(k, bool(c.get("nether")), "planks") for k, c in classes.items()] + ["minecraft:bamboo_planks"])
    files[T.format(ns="tfcreate", kind="item", path="andesite_casing_woods")] = tag_json(
        [vanilla(k, bool(c.get("nether")), x) for k, c in classes.items() for x in ("stripped_log", "stripped_wood")])
    files[T.format(ns="tfc", kind="item", path="workbenches")] = tag_json(["minecraft:crafting_table"])
    files[T.format(ns="tfc", kind="block", path="workbenches")] = tag_json(["minecraft:crafting_table"])
    files[T.format(ns="c", kind="item", path="barrels/wooden")] = tag_json(["#tfc:barrels"])

    # W vanilla trees in TFC forests
    W = os.path.join(KDATA, "firmages", "worldgen")
    wg = table["worldgen"]
    forest = {"forest": [], "mangrove": []}
    for k, c in classes.items():
        t = c.get("tree")
        if not t:
            continue
        sap = t["sapling"]
        placed = []
        for f in t["features"]:
            if f in CUSTOM_TREES:
                tree = CUSTOM_TREES[f]()
                for name in re.findall(r'"Name": "([a-z0-9_:/]+)"', json.dumps(tree)):
                    need(name)   # an unknown block id fails the whole worldgen registry at boot
                files[os.path.join(W, "configured_feature", *f.split(":")[1].split("/")) + ".json"] = tree
            pid = f"firmages:vanilla_tree/{k}/{f.split('/')[-1].split(':')[-1]}"
            files[os.path.join(W, "placed_feature", *pid.split(":")[1].split("/")) + ".json"] = \
                {"feature": f, "placement": [would_survive(sap)]}
            placed.append(pid)
